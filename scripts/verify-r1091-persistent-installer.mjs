import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const file='PhotoBridge-Store-R1089-Setup-1.0.3-x64.exe';
const zipName=file.replace(/\.exe$/,'.zip');
const dir=path.join(root,'dist','web','downloads','store-desktop');
const exe=path.join(dir,file),zip=path.join(dir,zipName);
const manifest=JSON.parse(fs.readFileSync(path.join(root,'dist','installer-source','store-r1089','manifest.json'),'utf8'));
assert.equal(fs.statSync(exe).size,manifest.size,'source installer must be complete, not a stub');
const sha=crypto.createHash('sha256');
for await(const chunk of fs.createReadStream(exe))sha.update(chunk);
assert.equal(sha.digest('hex'),manifest.sha256,'source installer matches Windows CI');
const stat=fs.statSync(zip),filenameBytes=Buffer.byteLength(file);
assert.equal(stat.size,manifest.size+98+2*filenameBytes,'ZIP must contain exactly the full installer');
const fd=fs.openSync(zip,'r');
const hdr=Buffer.alloc(30+filenameBytes);
try{fs.readSync(fd,hdr,0,hdr.length,0)}finally{fs.closeSync(fd)}
assert.equal(hdr.readUInt32LE(0),0x04034b50,'valid ZIP local header');
assert.equal(hdr.readUInt16LE(8),0,'stored ZIP method for WinRAR and Explorer compatibility');
assert.equal(hdr.readUInt32LE(18),manifest.size,'ZIP full uncompressed file size');
assert.equal(hdr.readUInt32LE(22),manifest.size,'ZIP full compressed file size');
assert.equal(hdr.readUInt16LE(26),filenameBytes,'filename length');
assert.equal(hdr.subarray(30).toString(),file,'ZIP contains only the installer EXE');
const insideSha=crypto.createHash('sha256');
const dataStart=hdr.length;
for await(const chunk of fs.createReadStream(zip,{start:dataStart,end:dataStart+manifest.size-1}))
  insideSha.update(chunk);
assert.equal(insideSha.digest('hex'),manifest.sha256,'installer inside ZIP must match verified EXE exactly');
const js=fs.readFileSync(path.join(root,'dist','web','photobridge-store-desktop-install-r60.js'),'utf8');
assert(js.includes('/downloads/store-desktop/'+zipName),'the store settings must link first-party ZIP');
assert(!js.includes('/downloads/store-desktop/'+file+"'"),'the store settings must not download EXE directly');
assert(!js.includes('نسخه آزمایشی'),'remove trial banner text from compact installer card');
assert(!js.includes('actions/runs/38084340638/artifacts'),'no expiring GitHub artifact links');
const portal=fs.readFileSync(path.join(root,'dist','api','equipment-rental-portal.html'),'utf8');
assert(!portal.includes('<div class="box pb842WindowsAlertBox">'),'old Windows alert pairing card must be removed');
assert(!portal.includes('id="createRentalAlertAgent"'),'old connection code button must be removed');
assert(portal.includes('id="shopForm"'),'store settings remain intact');
const docker=fs.readFileSync(path.join(root,'.dockerignore'),'utf8');
assert(docker.includes('!dist/**'),'versioned installer source must enter Docker build');
console.log('PASS: persistent Windows ZIP, EXE inside matches SHA256, old alert panel removed. ZIP bytes:',stat.size);
