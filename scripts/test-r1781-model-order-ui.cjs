'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const crypto=require('node:crypto');
test('R1781: photographer and public walk-in have model picker, immutable upload identifiers and colour',()=>{
 const ui=fs.readFileSync('dist/web/assets/index-UIRefine-v655-r84.js','utf8');
 const html=fs.readFileSync('dist/web/index.html','utf8');
 const css=fs.readFileSync('dist/web/photobridge-r1781-model-order-ui.css','utf8');
 assert(ui.includes('/* PB1781 PHOTO MODEL CHOOSERS */'));
 assert(ui.includes('function PB1781ChassisSelector('));
 assert(ui.includes('function PB1777FrameSelector('));
 assert(ui.includes('pb1781SetPicker({groupId:ue.id,fileId:Be.id,kind:"frame"})'));
 assert(ui.includes('[pick.kind+"Override"]:"1"'),"a photo-level model choice must activate that add-on");
 assert(ui.includes('pb1781SetPicker({fileId:me.id,kind:"frame"})'));
 assert(ui.includes('chassisModelId:yt?(tt.chassisModelId||"chassis"):null'));
 assert(ui.includes('frameColorId:Tt?(tt.frameColorId||null):null'));
 assert(ui.includes('chassisModelId:Z.chassis?(Z.chassisModelId||"chassis"):null'));
 assert(ui.includes('frameColorId:Z.frame?(Z.frameColorId||null):null'));
 assert(ui.includes('withoutPrint:!!(tt.withoutPrint&&(yt||Tt))'));
 assert(ui.includes('withoutPrint:!!(tt.withoutPrint&&(yt||Tt)),cropHandling:"lab"'),'model identifiers must preserve current delegated crop handling');
 assert(ui.includes('withoutPrint:!!(Z.withoutPrint&&(Z.chassis||Z.frame))'));
 assert(html.includes('/photobridge-r1781-model-order-ui.css?v=r1781'));
 assert(html.includes('modelOrder=r1781'));
 assert(css.includes('@media(max-width:380px)'));
 assert(ui.includes('none:"بدون چاپ عکس"'));
 const native=fs.readFileSync('dist/web/lab-desktop-ui/assets/index-UIRefine-v655-r84.js','utf8');
 const manifest=JSON.parse(fs.readFileSync('dist/web/lab-desktop-ui/manifest.json','utf8'));
 const entry=manifest.files.find(x=>x.name==='assets/index-UIRefine-v655-r84.js');
 assert(native.includes('none:"بدون چاپ عکس"'));
 assert.equal(entry.sha256,crypto.createHash('sha256').update(native).digest('hex'));
});
