/* PhotoBridge R100F15 — leave Print cleanly when another photographer tab is selected. */
(()=>{
  'use strict';
  if(window.__PB_R100F15_PRINT_EXIT__)return;
  window.__PB_R100F15_PRINT_EXIT__=true;

  const q=(s,r=document)=>r?.querySelector?.(s)||null;
  const onPhotographer=()=>/^\/photographer(?:\/|$)/.test(location.pathname);
  const printContext=()=>new URLSearchParams(location.search).get('workspace')==='print'||!!q('.photographerMain.photographerPrintWorkspace');
  const nonPrintPath=p=>/^\/photographer\/(?:ai|gallery|album-design|wallet|settings|labs)(?:\/|$)/.test(p);
  const cleanupQuery=url=>{
    const u=new URL(url,location.href);
    if(nonPrintPath(u.pathname)){
      u.searchParams.delete('workspace');
      u.searchParams.delete('pbLabChooser');
      u.searchParams.delete('pbEntryDone');
    }
    return `${u.pathname}${u.search}${u.hash}`;
  };
  function clearRuntime(){
    document.documentElement.classList.remove('pb817PrintContext','pb817PrintFinance','pb818PrintContext','pb818PrintFinance','pb821PrintFinance','pbR100F14LabChooserBoot');
    document.body.classList.remove('pb737-mobile-print-active','pbR100F14ChoosingLab');
    for(const id of ['pb762-add','pb765-add','pb742-print-actions','pb737-mobile-print-dock','pb761-mode-actions'])document.getElementById(id)?.remove();
    document.getElementById('pbR99LabChooser')?.remove();
    document.documentElement.style.removeProperty('overflow');
    document.body.style.removeProperty('overflow');
  }
  function routeTo(path,designMode){
    clearRuntime();
    try{if(designMode!==undefined)window.__PB_PUBLIC_DESIGN_MODE__=designMode}catch{}
    const dest=cleanupQuery(path);
    history.pushState(null,'',dest);
    window.dispatchEvent(new PopStateEvent('popstate',{state:history.state}));
    // Some older runtime layers also listen on a synthetic route event.
    window.dispatchEvent(new Event('pb726routechange'));
    // One extra sync after React's state update prevents a stale Print header from surviving.
    requestAnimationFrame(()=>window.dispatchEvent(new PopStateEvent('popstate',{state:history.state})));
  }
  function targetFor(button){
    const label=String(button?.getAttribute?.('aria-label')||button?.querySelector?.('em')?.textContent||button?.textContent||'').replace(/\s+/g,' ').trim();
    if(label==='هوش مصنوعی')return ['/photographer/ai/retouch',undefined];
    if(label==='گالری'||label==='گالری مشتریان')return ['/photographer/gallery',undefined];
    if(label==='طراحی آلبوم')return ['/photographer/album-design',''];
    if(label==='اینستاگرام')return ['/photographer/album-design?pb_mode=instagram','instagram'];
    return null;
  }

  // Own only exits from Print. Normal navigation elsewhere remains untouched.
  document.addEventListener('click',e=>{
    if(!onPhotographer()||!printContext())return;
    const b=e.target?.closest?.('.photographerBottomAppNavGrid>button,.photographerHomeModeNav>button');
    if(!b)return;
    const target=targetFor(b);if(!target)return;
    e.preventDefault();e.stopPropagation();e.stopImmediatePropagation?.();
    routeTo(target[0],target[1]);
  },true);

  // Defensive route healing for history transitions generated by older layers.
  function heal(){
    if(!onPhotographer()||!nonPrintPath(location.pathname))return;
    const here=cleanupQuery(location.href);
    if(here!==`${location.pathname}${location.search}${location.hash}`)history.replaceState(history.state,'',here);
    clearRuntime();
  }
  for(const name of ['pushState','replaceState']){
    const old=history[name];if(typeof old!=='function'||old.__pbR100F15)continue;
    const fn=function(state,title,url){
      const clean=url==null?url:cleanupQuery(url);
      const out=old.call(this,state,title,clean);
      queueMicrotask(heal);return out;
    };fn.__pbR100F15=true;history[name]=fn;
  }
  addEventListener('popstate',()=>queueMicrotask(heal),{passive:true});
  addEventListener('pageshow',heal,{passive:true});
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',heal,{once:true});else heal();
})();
